# ============================================================
# app/models/user.py — User & Role ORM Models
#
# ARCHITECT'S NOTE:
#   SQLAlchemy ORM models define the database schema.
#   These become actual PostgreSQL tables via Alembic migrations.
#
#   Enterprise RBAC (Role-Based Access Control) design:
#     - A User belongs to exactly one Team
#     - A User has one Role (admin, manager, member)
#     - Roles control which LLM models the user can access
#       and what budget they have
#
#   The Role enum maps directly to LiteLLM virtual key settings.
# ============================================================

from sqlalchemy import (
    Column, String, Boolean, DateTime, Enum as SAEnum,
    ForeignKey, func, Text
)
from sqlalchemy.orm import relationship
from sqlalchemy.dialects.postgresql import UUID
import uuid
import enum

from app.database import Base


class UserRole(str, enum.Enum):
    """
    Enterprise roles — determines model access and budget limits.
    'str' mixin ensures JSON serialization works (role.value is a plain string).
    """
    SUPER_ADMIN = "super_admin"   # platform-wide admin (IT/DevOps)
    TEAM_ADMIN  = "team_admin"    # manages a single team (department head)
    MEMBER      = "member"        # regular employee


class User(Base):
    """
    Core user model.
    Every authenticated request is tied to a User row.
    """
    __tablename__ = "users"

    # Primary key uses UUID rather than sequential int —
    # UUIDs are safe to expose in URLs and avoid enumeration attacks
    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )

    email = Column(String(255), unique=True, nullable=False, index=True)
    full_name = Column(String(255), nullable=False)

    # Bcrypt hash — the plaintext password is NEVER stored
    hashed_password = Column(String(255), nullable=False)

    role = Column(
        SAEnum(UserRole, name="user_role_enum"),
        nullable=False,
        default=UserRole.MEMBER,
    )

    # Department / team membership
    # ForeignKey to teams table — set when admin onboards the user
    team_id = Column(
        UUID(as_uuid=True),
        ForeignKey("teams.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # LiteLLM assigns a virtual key per user so usage is tracked individually.
    # This field stores that key — it is generated by the LiteLLM proxy API
    # when the user is created and must be kept secret (treat like a password).
    litellm_virtual_key = Column(String(255), nullable=True)

    is_active = Column(Boolean, default=True, nullable=False)

    # Timestamps — always store in UTC, convert to user timezone in the UI
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    last_login_at = Column(DateTime(timezone=True), nullable=True)

    # -------------------------------------------------------
    # Relationships — SQLAlchemy loads these lazily by default.
    # For performance in async code, always use selectinload() or
    # joinedload() in queries rather than accessing .team blindly.
    # -------------------------------------------------------
    team = relationship("Team", back_populates="members")
    chat_sessions = relationship("ChatSession", back_populates="user", cascade="all, delete-orphan")

    def __repr__(self) -> str:
        return f"<User {self.email} ({self.role})>"
